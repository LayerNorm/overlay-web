#!/usr/bin/env bash
# First-run bootstrap for the self-hosted Convex backend.
#
# Prerequisites:
#   - docker compose -f docker-compose.convex.yml --env-file convex.env up -d
#   - backend healthy (curl http://<host>:3210/version returns 200)
#   - node + npx available locally, run from the overlay repo root
#
# Does:
#   1. Generates the deployment admin key inside the backend container.
#   2. Writes a local CLI env file (gitignored name) with the self-hosted
#      endpoint + admin key.
#   3. Deploys the full convex/ function tree.
#   4. Sets INTERNAL_API_SECRET + INTERNAL_SERVICE_AUTH_SECRET on the
#      deployment (must match the app env exactly).
#
# Usage:
#   ./bin/convex-bootstrap.sh \
#     --compose-dir examples/customer-deployment \
#     --api-secret <INTERNAL_API_SECRET> \
#     --service-secret <INTERNAL_SERVICE_AUTH_SECRET>
set -euo pipefail

COMPOSE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="convex.env"
CLI_ENV_OUT=".env.convex.local"
API_SECRET=""
SERVICE_SECRET=""
EXTRA_ENV=()  # additional KEY=VALUE pairs set on the deployment

while [[ $# -gt 0 ]]; do
  case "$1" in
    --compose-dir) COMPOSE_DIR="$2"; shift 2 ;;
    --env-file) ENV_FILE="$2"; shift 2 ;;
    --out) CLI_ENV_OUT="$2"; shift 2 ;;
    --api-secret) API_SECRET="$2"; shift 2 ;;
    --service-secret) SERVICE_SECRET="$2"; shift 2 ;;
    --set) EXTRA_ENV+=("$2"); shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 1 ;;
  esac
done

COMPOSE=(docker compose -f "$COMPOSE_DIR/docker-compose.convex.yml" --env-file "$COMPOSE_DIR/$ENV_FILE")

echo "==> waiting for backend health"
for i in $(seq 1 60); do
  if "${COMPOSE[@]}" exec -T backend curl -sf http://localhost:3210/version >/dev/null 2>&1; then
    break
  fi
  [[ $i -eq 60 ]] && { echo "backend never became healthy" >&2; exit 1; }
  sleep 2
done
echo "    backend healthy"

echo "==> generating admin key"
ADMIN_KEY=$("${COMPOSE[@]}" exec -T backend ./generate_admin_key.sh 2>/dev/null | tr -d '[:space:]')
# Key shape is "<INSTANCE_NAME>|<hex>" — derive the expected prefix from the
# backend env rather than assuming the default instance name.
EXPECTED_PREFIX=$("${COMPOSE[@]}" exec -T backend sh -c 'echo "${INSTANCE_NAME:-convex-self-hosted}"' | tr -d '[:space:]')
[[ "$ADMIN_KEY" == "$EXPECTED_PREFIX|"* ]] || { echo "unexpected admin key shape" >&2; exit 1; }

# Resolve the API origin the CLI should target (defaults to local port).
API_URL=$("${COMPOSE[@]}" exec -T backend sh -c 'echo "${CONVEX_CLOUD_ORIGIN:-http://127.0.0.1:3210}"' | tr -d '[:space:]')

cat > "$COMPOSE_DIR/$CLI_ENV_OUT" <<EOF
# Generated by bin/convex-bootstrap.sh — local CLI credentials for the
# self-hosted deployment. Do NOT commit. Rotate by re-running bootstrap.
CONVEX_SELF_HOSTED_URL=$API_URL
CONVEX_SELF_HOSTED_ADMIN_KEY=$ADMIN_KEY
EOF
chmod 600 "$COMPOSE_DIR/$CLI_ENV_OUT"
echo "    wrote $COMPOSE_DIR/$CLI_ENV_OUT (chmod 600)"

echo "==> deploying convex/ function tree"
CONVEX_DEPLOYMENT= npx convex deploy --env-file "$COMPOSE_DIR/$CLI_ENV_OUT" -y

set_env() {
  local name="$1" value="$2"
  [[ -n "$value" ]] || return 0
  CONVEX_DEPLOYMENT= npx convex env set "$name" "$value" --env-file "$COMPOSE_DIR/$CLI_ENV_OUT" >/dev/null
  echo "    set $name"
}

echo "==> setting deployment env"
set_env INTERNAL_API_SECRET "$API_SECRET"
set_env INTERNAL_SERVICE_AUTH_SECRET "$SERVICE_SECRET"
for kv in "${EXTRA_ENV[@]:-}"; do
  [[ -n "$kv" ]] && set_env "${kv%%=*}" "${kv#*=}"
done

cat <<EOF

Done. Next steps:
  1. Point the app at this backend:
       NEXT_PUBLIC_CONVEX_URL=$API_URL
       INTERNAL_API_SECRET + INTERNAL_SERVICE_AUTH_SECRET matching the values above
  2. First user sign-up runs normal onboarding (seeds subscription + member role).
  3. Cron jobs, scheduled functions, and file storage are already live.
  4. Optional dashboard: docker compose -f docker-compose.convex.yml --env-file convex.env --profile dashboard up -d
EOF
