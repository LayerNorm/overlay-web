"""Outline the real font in a shared coordinate system, including its kerning."""
from pathlib import Path
import shutil

from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from PIL import ImageFont, features

directory = Path(__file__).resolve().parent
root = directory.parents[2]
font_path = root / 'public/assets/fonts/Libre_Baskerville/static/LibreBaskerville-Regular.ttf'
font = TTFont(font_path)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
units = font['head'].unitsPerEm
assert features.check('raqm'), 'RAQM is required for the font’s native kerning'
shaper = ImageFont.truetype(str(font_path), units, layout_engine=ImageFont.Layout.RAQM)
word = 'Overlay'
baseline = 830
tracking = -25
icon_gap = 3 * units / 40
paths = []
bounds = {}
for index, character in enumerate(word):
    glyph = glyphs[cmap[ord(character)]]
    x = shaper.getlength(word[:index + 1]) - shaper.getlength(character) + tracking * index
    if index > 0:
        x += icon_gap
    transform = (1, 0, 0, -1, x, baseline)
    pen = SVGPathPen(glyphs)
    glyph.draw(TransformPen(pen, transform))
    box = BoundsPen(glyphs)
    glyph.draw(TransformPen(box, transform))
    bounds[character] = box.bounds
    paths.append(f'<path data-glyph="{character}" d="{pen.getCommands()}"/>')

# Round letters share the font's ten-unit optical overshoot below its baseline.
assert bounds['O'][3] == bounds['e'][3] == bounds['a'][3] == baseline + 10
assert bounds['r'][3] == bounds['l'][3] == baseline
eyes = 'M347.0 -447.0A46.0 46.0 0 0 1 439.0 -447.0L439.0 -363.0A46.0 46.0 0 0 1 347.0 -363.0ZM507.0 -447.0A46.0 46.0 0 0 1 599.0 -447.0L599.0 -363.0A46.0 46.0 0 0 1 507.0 -363.0Z'
paths.insert(1, f'<g class="brand-eyes"><path data-eyes="" transform="translate(0 {baseline})" d="{eyes}"/></g>')
icon_scale = 1.05
icon_center = (bounds['O'][0] + bounds['O'][2]) / 2
icon_bottom = bounds['O'][3]
paths[:2] = [f'<g data-brand-icon="" transform="translate({icon_center} {icon_bottom}) scale({icon_scale}) translate({-icon_center} {-icon_bottom})">' + ''.join(paths[:2]) + '</g>']
left = min(b[0] for b in bounds.values())
right = max(b[2] for b in bounds.values())
bottom = max(b[3] for b in bounds.values())
width = right - left
guide_y = bounds['v'][3]
geometry = f'viewBox="{left} 0 {width} {bottom}"'
reference_width = width - icon_gap
reference_geometry = f'viewBox="{left} 0 {reference_width} {bottom}"'
icon_drop = 2 * units / 40
body = f'<g transform="translate(0 {icon_drop})">{paths[0]}</g>' + ''.join(paths[1:])
jsx_body = body.replace('class=', 'className=')
icon_body = paths[0]
jsx_icon = icon_body.replace('class=', 'className=')
icon_ink_left = icon_center + (bounds['O'][0] - icon_center) * icon_scale
icon_ink_right = icon_center + (bounds['O'][2] - icon_center) * icon_scale
icon_ink_top = icon_bottom + (bounds['O'][1] - icon_bottom) * icon_scale
icon_side = icon_ink_right - icon_ink_left + 64
icon_top = (icon_ink_top + icon_bottom - icon_side) / 2
icon_box = f'{icon_ink_left - 32} {icon_top} {icon_side} {icon_side}'
svg = f'<svg xmlns="http://www.w3.org/2000/svg" {geometry} overflow="visible" fill="currentColor" role="img" aria-label="Overlay">{body}</svg>'
(directory / 'aligned-brand.svg').write_text(svg + '\n')
assets = directory / 'overlay-brand-approved'
assets.mkdir(exist_ok=True)
wordmark_box = f'{icon_ink_left - 32} -32 {right - icon_ink_left + 64} {bottom + 64}'
for name, box, content in [('wordmark', wordmark_box, body), ('icon', icon_box, icon_body)]:
    for suffix, color in [('', 'currentColor'), ('-black', '#000000'), ('-white', '#ffffff')]:
        (assets / f'overlay-{name}{suffix}.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box}" fill="{color}" role="img" aria-label="Overlay">{content}</svg>\n')
shutil.copyfile(font_path.parents[1] / 'OFL.txt', assets / 'FONT-LICENSE.txt')
component = f'''// Generated by build-aligned-brand.py from the repository's Libre Baskerville font.
export function AlignedBrandLockup({{ guide = false, motion = 'none' }}: {{ guide?: boolean; motion?: 'none' | 'look' }}) {{
  return <svg {geometry} fill="currentColor" role="img" aria-label="Overlay" className={{motion === 'look' ? 'aligned-brand-lockup brand-eyes-look' : 'aligned-brand-lockup'}} style={{{{ width: '{width / units}em', height: '{bottom / units}em' }}}}>
    {jsx_body}
    {{guide && <path data-alignment-guide="v-bottom" d="M{left} {guide_y}H{right}" stroke="#5b9fda" strokeWidth="1" vectorEffect="non-scaling-stroke" fill="none" aria-hidden="true"/>}}
  </svg>
}}
export function LibreBaskervilleWordmark({{ guide = false }}: {{ guide?: boolean }}) {{
  return <svg {reference_geometry} fill="currentColor" role="img" aria-label="Overlay in Libre Baskerville" className="aligned-brand-lockup" style={{{{ width: '{reference_width / units}em', height: '{bottom / units}em' }}}}>
    <text x="0" y="{baseline}" fontFamily="Libre Baskerville" fontSize="{units}" fontWeight="400" letterSpacing="{tracking}">Overlay</text>
    {{guide && <path d="M{left} {guide_y}H{right - icon_gap}" stroke="#5b9fda" strokeWidth="1" vectorEffect="non-scaling-stroke" fill="none" aria-hidden="true"/>}}
  </svg>
}}
export function ApprovedOverlayMark({{ size = 20, motion = 'none' }}: {{ size?: number; motion?: 'none' | 'look' }}) {{
  return <svg viewBox="{icon_box}" width={{size}} height={{size}} fill="currentColor" role="img" aria-label="Overlay" className={{motion === 'look' ? 'brand-eyes-look' : undefined}}>{jsx_icon}</svg>
}}
'''
(directory / 'aligned-brand.tsx').write_text(component)
production = f'''// Generated by internal/plans/mockups/build-aligned-brand.py; do not edit the outlines by hand.
import React, {{ type SVGProps }} from 'react'

type BrandShapeProps = SVGProps<SVGSVGElement> & {{ motion?: 'none' | 'blink' | 'look' }}

export function ApprovedBrandWordmark({{ motion = 'none', className = '', ...props }}: BrandShapeProps) {{
  return <svg viewBox="{left} 0 {width} {bottom}" width="{width / units}em" height="{bottom / units}em" fill="currentColor" {{...props}} className={{`approved-brand approved-brand--${{motion}} ${{className}}`}}>
    {jsx_body}
  </svg>
}}

export function ApprovedBrandIcon({{ motion = 'none', className = '', ...props }}: BrandShapeProps) {{
  return <svg viewBox="{icon_box}" fill="currentColor" {{...props}} className={{`approved-brand approved-brand--${{motion}} ${{className}}`}}>
    {jsx_icon}
  </svg>
}}
'''
(root / 'packages/overlay-ui/src/components/orb/ApprovedBrand.tsx').write_text(production)
print(f'Generated shared SVG: O bottom = {icon_bottom + icon_drop}; e/a bottom = {baseline + 10}; r/l baseline = {baseline}; y descender = {bottom}.')
