// Writes lucide-react.generated.tsx: one export per Lucide icon the app imports, drawn with the Hugeicons outline
// that map.json names. The outlines are copied in, so building the mockup needs no new dependency.
//   npm install --prefix /tmp/hugeicons @hugeicons/core-free-icons
//   HUGEICONS_DIR=/tmp/hugeicons node internal/plans/mockups/overlay-app/features/hugeicons/generate.mjs
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = fileURLToPath(new URL('./', import.meta.url))
const icons = createRequire(path.join(path.resolve(process.env.HUGEICONS_DIR ?? '.'), 'index.js'))('@hugeicons/core-free-icons')
const map = JSON.parse(await readFile(path.join(here, 'map.json'), 'utf8'))

const lines = Object.entries(map).map(([lucide, huge]) => {
  const outline = icons[huge]
  if (!outline) throw new Error(`${lucide}: Hugeicons has no ${huge}`)
  const elements = outline.map(([tag, { key, ...attributes }]) => [tag, attributes])
  return `export const ${lucide} = icon('${huge}', ${JSON.stringify(elements)})`
})

await writeFile(
  path.join(here, 'lucide-react.generated.tsx'),
  `// Generated by generate.mjs from map.json. Outlines: Hugeicons free set (MIT, © Hugeicons).\nimport { icon } from './icon'\n\nexport type { LucideIcon, LucideProps } from './icon'\n\n${lines.join('\n')}\n`,
)
console.log(`Wrote ${lines.length} icons`)
