import { useCallback, useState, type CSSProperties } from 'react'
import { AlertCircle, Download, Play } from 'lucide-react'
import type { GenerationResult } from '@overlay/chat-core'

type MediaGenType = 'image' | 'video'

function singleMediaBoxStyle(genType: MediaGenType): CSSProperties {
  return genType === 'image'
    ? { width: 208, height: 208, minWidth: 208, minHeight: 208, boxSizing: 'border-box' }
    : { width: 288, height: 160, minWidth: 288, minHeight: 160, boxSizing: 'border-box' }
}

function MediaElement({
  genType,
  url,
  modelName,
  ready,
  onReady,
}: {
  genType: MediaGenType
  url: string
  modelName: string
  ready: boolean
  onReady: () => void
}) {
  if (genType === 'image') {
    return (
      <img
        src={url}
        alt={`Generated by ${modelName}`}
        onLoad={onReady}
        onError={onReady}
        className={`absolute inset-0 z-20 block h-full w-full rounded-xl border border-(--border) object-contain transition-opacity duration-300 ease-out ${
          ready ? 'opacity-100' : 'opacity-0'
        }`}
      />
    )
  }
  return (
    <video
      src={url}
      controls
      preload="metadata"
      playsInline
      onLoadedData={onReady}
      onLoadedMetadata={onReady}
      onCanPlay={onReady}
      onError={onReady}
      className={`absolute inset-0 z-20 block h-full w-full rounded-xl border border-(--border) transition-opacity duration-300 ease-out ${
        ready ? 'opacity-100' : 'opacity-0'
      }`}
    />
  )
}

function MediaHoverOverlay({
  genType,
  url,
  modelName,
}: {
  genType: MediaGenType
  url: string
  modelName: string
}) {
  return (
    <>
      <div className="pointer-events-none absolute inset-x-0 top-0 z-30 h-16 bg-linear-to-b from-black/55 via-black/18 to-transparent opacity-0 transition-opacity duration-200 group-hover:opacity-100" />
      <div className="absolute inset-x-0 top-0 z-40 flex items-start justify-between gap-3 p-2.5 opacity-0 transition-opacity duration-200 group-hover:opacity-100">
        <span className="min-w-0 rounded-full bg-black/30 px-2.5 py-1 text-[11px] font-medium leading-none text-white/95 backdrop-blur-[1px]">
          <span className="block truncate">{modelName}</span>
        </span>
        <a
          href={url}
          download={genType === 'image' ? 'generated.png' : 'generated.mp4'}
          className="pointer-events-auto shrink-0 rounded-full bg-(--glass-bg) p-1.5 shadow-xs transition-colors hover:bg-(--surface-elevated)"
          title="Download"
        >
          <Download size={13} className="text-(--foreground)" />
        </a>
      </div>
    </>
  )
}

function VideoPlayBadge({ ready }: { ready: boolean }) {
  return (
    <div className="pointer-events-none absolute inset-0 z-10 flex items-center justify-center transition-opacity duration-300 ease-out group-hover:opacity-0">
      <span className={`inline-flex h-11 w-11 items-center justify-center rounded-full bg-black/45 text-white shadow-xs transition-opacity duration-300 ${
        ready ? 'opacity-100' : 'opacity-0'
      }`}>
        <Play size={16} fill="currentColor" />
      </span>
    </div>
  )
}

/** Single image/video cell: mesh placeholder while generating; crossfade to media after load. */
const upgradeLink = (
  // Internal nav without Link — this package has no next/ dependency.
  // react-doctor-disable-next-line react-doctor/nextjs-no-a-element
  <a href='/pricing' className='underline underline-offset-2 hover:opacity-70'>
    Upgrade here
  </a>
)

export function MediaSlotOutput({
  genType,
  modelName,
  result,
}: {
  genType: 'image' | 'video'
  modelName: string
  result: GenerationResult | undefined
}) {
  const singleBoxStyle = singleMediaBoxStyle(genType)

  return (
    <div className="flex min-w-0 flex-col gap-2 self-start">
      {!result || result.status === 'generating' ? (
        <p className="text-xs font-medium text-(--muted)">
          {genType === 'image' ? 'Creating image' : 'Creating video'}
        </p>
      ) : null}

      {!result || result.status === 'generating' ? (
        <div
          className="media-gen-mesh box-border shrink-0 overflow-hidden rounded-xl border border-(--border)"
          style={singleBoxStyle}
          aria-hidden
        />
      ) : result.status !== 'completed' || !result.url ? (
        <div
          className="flex items-center gap-2 rounded-xl border px-3 py-2 text-xs"
          style={{
            ...singleBoxStyle,
            background: 'var(--chat-media-error-bg)',
            borderColor: 'var(--chat-media-error-border)',
            color: 'var(--chat-alert-error-text)',
          }}
        >
          {
            // Internal nav without Link — this package has no next/ dependency.
            // react-doctor-disable-next-line react-doctor/nextjs-no-a-element
          }
          <AlertCircle size={12} />
          {result.upgradeRequired ? (
            <>
              <span>
                {genType === 'image' ? 'Image' : 'Video'} generation
                requires a paid plan.{' '}
              </span>
              {upgradeLink}
            </>
          ) : (
            (result.error ?? 'Failed')
          )}
        </div>
      ) : (
        <MediaCompletedReveal
          key={result.url}
          genType={genType}
          modelName={modelName}
          url={result.url}
        />
      )}
    </div>
  )
}

export function MediaCompletedReveal({
  genType,
  modelName,
  url,
}: {
  genType: MediaGenType
  modelName: string
  url: string
}) {
  const [ready, setReady] = useState(false)
  const markReady = useCallback(() => setReady(true), [])

  return (
    <div
      className="relative group max-w-full shrink-0 overflow-hidden rounded-xl border border-(--border) bg-(--surface-muted)"
      style={singleMediaBoxStyle(genType)}
    >
      <div
        className={`media-gen-mesh media-gen-mesh--fill pointer-events-none z-10 rounded-xl transition-opacity duration-300 ease-out ${
          ready ? 'opacity-0' : 'opacity-100'
        }`}
        aria-hidden
      />
      <MediaElement
        genType={genType}
        url={url}
        modelName={modelName}
        ready={ready}
        onReady={markReady}
      />
      <MediaHoverOverlay genType={genType} url={url} modelName={modelName} />
      {genType === 'video' && (
        <VideoPlayBadge ready={ready} />
      )}
    </div>
  )
}
